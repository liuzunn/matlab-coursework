% 分子：1+z^4 → 系数向量 [1,0,0,0,1]
B1 = [1, 0, 0, 0, 1];
% 分母：z(z²+1)² = z^5 + 2z³ + z → 系数向量 [1,0,2,0,1,0]
A1 = [1, 0, 2, 0, 1, 0];
% 计算留数
[r1, p1, k1] = residue(B1, A1);

disp('表达式(1)的留数：'); disp(r1);
disp('奇点：'); disp(p1);

% 分子：5z³+3z²-2z+7 → 系数向量 [5,3,-2,7]
B2 = [5, 3, -2, 7];
% 分母：-4z³+8z+3 → 系数向量 [-4,0,8,3]
A2 = [-4, 0, 8, 3];
% 计算留数
[r2, p2, k2] = residue(B2, A2);

disp('表达式(2)的留数：'); disp(r2);
disp('奇点：'); disp(p2);